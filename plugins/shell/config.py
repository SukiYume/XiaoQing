# 即使管理员关闭启用列表，仍拒绝明显的复合 shell 语法和高风险误触形式。
DANGEROUS_PATTERNS: tuple[str, ...] = (
    r"[;&|`$]",  # 命令链接、管道、替换或变量扩展
    r"[\r\n]",  # 多行命令
    r">\s*>",  # 追加重定向
    r">\s*/",  # 重定向到根路径
    r"(?:^|\s)rm\s+-[^\s]*r[^\s]*f",
    r"(?:^|\s)mkfs(?:\.[^\s]+)?(?:\s|$)",
    r"(?:^|\s)dd\s+if=",
    r":\(\)\{",  # Fork bomb（进程递归炸弹）
    r"(?:^|\s)chmod\s+777(?:\s|$)",
)
